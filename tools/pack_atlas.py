#!/usr/bin/env python3
"""
Crop the raw Blender renders and pack them into WebP atlases.

  python3 tools/pack_atlas.py

Reads  tools/blender/_renders/*.png + meta.json
Writes assets/gfx/*.webp and js/gfx-manifest.js
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "tools", "blender", "_renders")
OUT = os.path.join(ROOT, "assets", "gfx")
os.makedirs(OUT, exist_ok=True)
PAGE = 4096
PAD = 2

meta = json.load(open(os.path.join(RAW, "meta.json")))


def crop_sprite(path):
    im = Image.open(path).convert("RGBA")
    a = im.getchannel("A").point(lambda v: 255 if v > 3 else 0)
    bbox = a.getbbox()
    if not bbox:
        return None, 0, 0
    x0, y0, x1, y1 = bbox
    cx = im.width / 2
    half = max(cx - x0, x1 - cx)
    l, r = int(cx - half), int(round(cx + half))
    return im.crop((max(0, l), y0, min(im.width, r), y1)), r - l, y1 - y0


def pack(group, items, scale=1.0):
    """items: list of (name, img). shelf-pack into pages."""
    items = sorted(items, key=lambda t: -t[1].height)
    pages, placed = [], {}
    x = y = shelf_h = 0
    cur = []
    for name, img in items:
        if scale != 1.0:
            img = img.resize((max(1, round(img.width * scale)), max(1, round(img.height * scale))), Image.LANCZOS)
        w, h = img.width + PAD, img.height + PAD
        if x + w > PAGE:
            x, y, shelf_h = 0, y + shelf_h, 0
        if y + h > PAGE:
            pages.append(cur)
            cur, x, y, shelf_h = [], 0, 0, 0
        cur.append((name, img, x, y))
        placed[name] = (len(pages), x, y, img.width, img.height)
        x += w
        shelf_h = max(shelf_h, h)
    pages.append(cur)
    files = []
    for pi, page in enumerate(pages):
        W = PAGE
        H = max(py + im.height for _, im, _, py in page)
        H = (H + 3) // 4 * 4
        sheet = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        for _, im, px, py in page:
            sheet.paste(im, (px, py))
        fn = f"{group}_{pi}.webp"
        sheet.save(os.path.join(OUT, fn), "WEBP", quality=90, method=6)
        files.append("assets/gfx/" + fn)
        print("page", fn, W, H)
    return files, placed


manifest = {"pages": [], "sprites": {}, "bgs": {}}

for group, scale in (("cars", 0.62), ("scenery", 1.0)):
    items, info = [], {}
    for name, m in meta.items():
        if m.get("group") != group:
            continue
        p = os.path.join(RAW, m["file"])
        if not os.path.exists(p):
            continue
        img, w, h = crop_sprite(p)
        if img is None:
            continue
        items.append((name, img))
        info[name] = (w / m["ppm"], h / m["ppm"])
    files, placed = pack(group, items, scale)
    base = len(manifest["pages"])
    manifest["pages"] += files
    for name, (pi, x, y, w, h) in placed.items():
        wm, hm = info[name]
        manifest["sprites"][name] = {"p": base + pi, "x": x, "y": y, "w": w, "h": h, "wm": round(wm, 3), "hm": round(hm, 3)}

for name, m in meta.items():
    if m.get("group") == "bg":
        im = Image.open(os.path.join(RAW, m["file"])).convert("RGBA")
        bbox = im.getchannel("A").getbbox()
        top = bbox[1] if bbox else 0
        im = im.crop((0, max(0, top - 2), im.width, im.height))
        im = im.resize((2048, max(1, round(im.height / 2))), Image.LANCZOS)
        fn = name + ".webp"
        im.save(os.path.join(OUT, fn), "WEBP", quality=88, method=6)
        manifest["bgs"][name] = {"src": "assets/gfx/" + fn, "w": im.width, "h": im.height}
    if m.get("group") == "hero":
        im = Image.open(os.path.join(RAW, m["file"])).convert("RGB")
        im.save(os.path.join(OUT, "hero.jpg"), "JPEG", quality=88)
        manifest["hero"] = "assets/gfx/hero.jpg"

js = "// generated by tools/pack_atlas.py — do not edit\nwindow.GFX_MANIFEST = " + json.dumps(manifest, separators=(",", ":")) + ";\n"
os.makedirs(os.path.join(ROOT, "js"), exist_ok=True)
open(os.path.join(ROOT, "js", "gfx-manifest.js"), "w").write(js)
print("sprites", len(manifest["sprites"]), "bgs", len(manifest["bgs"]))
